//Maps a canonical catalogue string to its translated label.
//
//The catalogue stores ENGLISH strings, and those English strings are what gets
//persisted to the backend. That is deliberate: a tag must mean the same thing
//no matter which language the user picked it in, or a Greek user's "Jazz" and
//an English user's "Jazz" would be two different values and matching would
//quietly break. Only the DISPLAY is translated, here, at the last moment.
//
//Anything with no entry falls back to the canonical string itself - which is
//correct for MBTI codes, brand names (Netflix, Disney) and the music genres
//Greek speakers write in Latin anyway.
//
//GENERATED-ish: if you add options to the catalogue, add their labels to the
//arb files and a line here.

import 'package:foitifinder/l10n/app_localizations.dart';

String catalogueLabel(AppLocalizations t, String canonical) {
  final resolver = _labels[canonical];
  return resolver == null ? canonical : resolver(t);
}

